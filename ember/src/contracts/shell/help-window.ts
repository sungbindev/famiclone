/** 可以直接打开的帮助页面：changelog 更新记录。 */
export type HelpPage = 'changelog';

/** 帮助文档窗口。 */
export interface HelpWindow {
  /** 打开帮助文档窗口；给了 page 时显示该页，没给时新窗口显示首页；已经打开时把它提到最前；文档不存在或窗口打不开时抛出带说明的异常。 */
  open(page?: HelpPage): Promise<void>;
  /** 关闭帮助文档窗口，没有打开时什么也不做。 */
  close(): void;
}
