/*
 * ------------------------------------------------------------------------
 * 名称：last-directories-service.ts
 * 说明：记住上次目录的服务契约：按用途记下用户在文件选择窗口里上次选定的目录，下次同一用途的窗口从那里打开。
 * 作者：sungbin
 * 邮箱：sungbin@3578.cn
 * 日期：2026-11-16
 * 备注：用途标识由调用文件选择窗口的代码给出（载入软盘镜像、打开卡带等各一个）；实现把它们保存到用户数据目录的本地文件（infra/last-directories）；
 *       记下的目录之后可能被删除或改名，窗口打不开它时由系统退回默认位置。
 * ------------------------------------------------------------------------
 */

/** 记住上次目录的服务。 */
export interface LastDirectoriesService {
  /** 某个用途上次选定的目录；没有记过时为 undefined。 */
  get(purpose: string): string | undefined;
  /** 记下某个用途选定的目录。 */
  set(purpose: string, directory: string): void;
  /** 立即写盘（应用退出前调用）。 */
  flush(): void;
}
