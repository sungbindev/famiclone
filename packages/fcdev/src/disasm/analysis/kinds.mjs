/** 字节分类 */
export const BYTE_KIND = Object.freeze({
  /** 没有被标成指令或地址表 */
  UNKNOWN: 0,
  /** 指令的第一个字节 */
  OPCODE: 1,
  /** 指令的操作数 */
  OPERAND: 2,
  /** 地址表里的字节，两个字节一个地址 */
  ADDRESS: 3,
});
