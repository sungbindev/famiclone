; 名称：bbgi-zeropage.s
; 说明：运行库使用的零页单元：两个公开的参数单元与几个库内部单元。
; 作者：sungbin
; 邮箱：sungbin@3578.cn
; 日期：2026-11-24
; 备注：零页放在链接配置的 ZEROPAGE 段（$0020-$007F）；调用者在调用库函数前把多出来的参数写进 bbg_arg0、
;       bbg_arg1，库函数不保留它们的内容。库内部单元（bbgi_ 开头）只在一次库函数调用内有效，调用者不要使用。
; ------------------------------------------------------------------------
        .exportzp       bbg_arg0, bbg_arg1
        .exportzp       bbgi_ptr, bbgi_flag, bbgi_index

        .zeropage

; 第二个 16 位参数（低字节在前）
bbg_arg0:       .res    2

; 第三个 16 位参数，或返回值的高 16 位
bbg_arg1:       .res    2

; 内部：指针与计算用的 16 位暂存
bbgi_ptr:       .res    2

; 内部：标志
bbgi_flag:      .res    1

; 内部：循环下标
bbgi_index:     .res    1
