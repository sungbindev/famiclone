        .code

; bbg_dos_exit
;   说明：DOS 调用 0：程序结束，回到命令行，不返回。
;   入口：A = 返回码
;   出口：不返回
bbg_dos_exit:
        tax
        ldy     #0
        lda     #DOS_PROGRAM_RETURN
        jmp     DOS_ENTRY
