        .include        "bbg.inc"

        .code

; bbg_dos_run_path
;   说明：DOS 调用 15：运行一个程序，文件名可以带路径。
;   入口：A（低）、X（高）= 以 0 结尾的路径与文件名地址（目录之间用 \ 分隔，文件名必须带扩展名 CMD、EXC 或 GAM）；Y = 程序所在盘号（0 默认盘，1 为 A 盘）；传给程序的参数先写在 $0100（长度）与 $0101 起（文本）
;   出口：同 bbg_dos_run
bbg_dos_run_path:
        sty     $FF
        tay
        lda     #DOS_RUN_PATH_PROGRAM
        jmp     DOS_ENTRY
