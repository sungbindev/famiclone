        .include        "bbg.inc"
        .import         bbgi_file_call

        .code

; bbg_file_drive
;   说明：文件调用 9：读取或设置默认驱动器。
;   入口：A（低）、X（高）= 文件通道块地址（FH_SIZE 字节，由调用者提供）；块里 FH_DRIVE 为 0 表示读取，否则为要设置的盘号（1 为 A 盘）
;   出口：C=0 成功，A=0；C=1 出错，A 为出错码；读取时 FH_DRIVE 为默认盘号，FH_DRIVE_COUNT 为逻辑驱动器数
bbg_file_drive:
        ldy     #FILE_DRIVE
        jmp     bbgi_file_call
