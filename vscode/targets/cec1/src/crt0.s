; ------------------------------------------------------------------------
; 名称：crt0.s
; 说明：中华学习机 CEC-I 的 DOS 3.3 二进制程序的启动代码：BRUN 把文件装到装入地址并从那里执行，
;       所以第一条指令放在装入地址上；初始化后调用 main，main 返回后跳到 DOS 的热启动入口回到命令行。
; 作者：sungbin
; 邮箱：sungbin@3578.cn
; 日期：2026-11-26
; 备注：不用 RTS 回到 DOS：DOS 3.3 进入程序前已经把自己的几层调用退了栈，返回时按进入 I/O 钩子时保存的栈指针
;       重新使用这一段栈，程序只要调用一次 COUT（钩子会重新保存栈指针）或者栈用得稍深，RTS 回去就会跑飞，
;       已用 Ember 里的 DOS 3.3 系统盘验证；热启动入口 $03D0 不依赖这些，回到 BASIC 的命令行，
;       内存里的 BASIC 程序保留。程序若是被 BASIC 程序里的 BRUN 调用，也回到命令行而不是继续那个 BASIC 程序。
; ------------------------------------------------------------------------
        .setcpu "6502"
        .export         __STARTUP__ : absolute = 1      ; 标记本文件是启动代码
        .import         _main
        .include        "cec1.inc"

        .segment        "STARTUP"

reset:  cld
        jsr     _main
        jmp     DOS_WARM_START                          ; 回到 DOS 的命令行，不会返回
