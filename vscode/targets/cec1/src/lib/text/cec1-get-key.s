        .include        "cec1.inc"

        .code

; cec1_get_key
;   说明：等待按键，返回按键码。
;   入口：无
;   出口：A = 按键的 ASCII 码（7 位）
cec1_get_key:
        jsr     MON_RDKEY
        and     #$7F
        rts
