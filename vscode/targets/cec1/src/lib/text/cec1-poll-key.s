; 备注：读键盘的软开关，位 7 为 1 时清除按键标志并返回按键码；没有按键返回 0；不保留 X、Y。
; ------------------------------------------------------------------------
        .include        "cec1.inc"

        .code

; cec1_poll_key
;   说明：不等待地检查键盘，有按键就取走。
;   入口：无
;   出口：A = 按键的 ASCII 码（7 位），没有按键为 0
cec1_poll_key:
        lda     KBD
        bpl     @none
        and     #$7F
        bit     KBDSTRB                 ; 清除按键标志，不改变 A
        rts
@none:  lda     #0
        rts
