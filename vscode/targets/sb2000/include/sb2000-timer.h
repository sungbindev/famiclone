/*
 * ------------------------------------------------------------------------
 * 名称：sb2000-timer.h
 * 说明：硬件定时器（$4034-$4036）与它的中断标志（$4032、$4033 的位 7）。
 * 作者：sungbin
 * 邮箱：sungbin@3578.cn
 * 日期：2026-11-13
 * 备注：由 sb2000.h 引入，程序不必单独包含。DOS 用这个定时器做系统时钟（开机时控制 $EF、预置值 $3C），改动它会影响 DOS 的计时，用完要用同样的值恢复。
 *       周期 = 基准周期 x (预分频 + 1) x (预置值 + 1)；基准是 CPU 时钟或行消隐时钟（15625Hz）。控制字节的位见 sb2000-symbols.h 里的 SB_HW_TIMER_ 常量。
 *       屏蔽与允许只改 $4032 的位 7，其余位保持 DOS 在影子里的值（写 1 的位会屏蔽该中断源并清除它的待处理标志，所以不能随便写 1，否则会丢掉已收到的键盘数据）。
 *       不重载的定时器下溢一次后当前值保持预置值，不再计时，也不再置标志。行为见 docs/sb2000/03-硬件说明.md。
 * ------------------------------------------------------------------------
 */
#ifndef SB2000_TIMER_H
#define SB2000_TIMER_H

/**
 * 设置并启动定时器：先写控制字节，再写预置值（预置值同时装入当前值）。
 *
 * @param control 控制字节：位 7 允许，位 6 连续重载（0 只计一次），位 5 行消隐时钟（0 是 CPU 时钟），位 3-0 预分频。
 * @param preset 预置值。
 */
void sb_timer_start(unsigned char control, unsigned char preset);

/**
 * 停止定时器：控制字节写 0。
 */
void sb_timer_stop(void);

/**
 * 读定时器当前值（递减）。
 *
 * @return 当前值。
 */
unsigned char sb_timer_current(void);

/**
 * 读定时器下溢标志（$4033 的位 7）。
 *
 * @return 1 已下溢；0 没有。
 */
unsigned char sb_timer_pending(void);

/**
 * 屏蔽定时器中断并清除下溢标志。
 */
void sb_timer_mask(void);

/**
 * 允许定时器中断：之后下溢时置标志，并产生中断（中断没有被关掉时）。
 */
void sb_timer_unmask(void);

#endif
